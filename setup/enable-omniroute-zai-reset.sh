#!/usr/bin/env bash
# enable-omniroute-zai-reset.sh — install and enable a systemd --user timer that runs
# scripts/zai-reset-weekly.sh every 5 minutes: it redeems a z.ai weekly-quota reset card once the
# weekly quota reaches 99 %, at most once per weekly window (see pylib/zai_reset.py).
set -euo pipefail
# shellcheck disable=SC1091 # Resolved from this script at runtime.
# shellcheck source=../tools/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/../tools/lib.sh"

require_cmd systemctl

[ -f "$CONFIG_PATH" ] || die "no config at ${CONFIG_PATH}; run 'make setup' first"

service_unit="${HOME}/.config/systemd/user/${ZAI_RESET_UNIT_NAME}.service"
timer_unit="${HOME}/.config/systemd/user/${ZAI_RESET_UNIT_NAME}.timer"
mkdir -p "$(dirname "$service_unit")"

cat > "$service_unit" <<EOT
# Generated by enable-omniroute-zai-reset.sh. Edits will be overwritten.
[Unit]
Description=llm-env z.ai weekly quota reset (redeems a reset card at 99 % weekly use)
After=network-online.target

[Service]
Type=oneshot
# systemd --user services do not inherit the interactive shell's PATH (uv lives under ~/.local/bin).
Environment=PATH=%h/.local/bin:/usr/local/bin:/usr/bin:/bin
ExecStart=/usr/bin/bash ${REPO_DIR}/scripts/zai-reset-weekly.sh
EOT
chmod 600 "$service_unit"
log_info "wrote ${service_unit}"

cat > "$timer_unit" <<EOT
# Generated by enable-omniroute-zai-reset.sh. Edits will be overwritten.
[Unit]
Description=Check every 5 minutes whether the z.ai weekly quota needs its reset card

[Timer]
OnBootSec=5min
OnUnitActiveSec=5min
Persistent=true

[Install]
WantedBy=timers.target
EOT
chmod 600 "$timer_unit"
log_info "wrote ${timer_unit}"

systemctl --user daemon-reload
systemctl --user enable --now "${ZAI_RESET_UNIT_NAME}.timer"
log_info "enabled ${ZAI_RESET_UNIT_NAME}.timer (every 5min; redeems a WEEK reset card at 99 % weekly use, once per window)"
log_info "run it now without redeeming: bash ${REPO_DIR}/scripts/zai-reset-weekly.sh --dry-run"
