_help_line "logs" "Follow service logs"
_help_line "validate" "Run shellcheck and ruff"
_help_line "test" "Run the Python test suite"
_help_line "clean" "Remove config, unit, and images"
_help_line "prune" "Remove config, unit, images, AND downloaded models (destructive)"
