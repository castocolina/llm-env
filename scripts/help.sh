    printf 'make %-32s%s\n' "$1" "$2"
}

_help_line "prerequisites" "Confirm and install host prerequisites"
_help_line "setup" "Interactive configuration"
_help_line "setup-local-llm-agents" "Configure normal Pi and OpenCode local providers"
_help_line "start" "Start whatever is not running (never stops a running container); installs the OmniRoute healer and z.ai reset timers"
_help_line "stop" "Stop the whole stack"
_help_line "restart" "Stop everything, re-render and start (applies config changes; interrupts requests)"
_help_line "start-llama" "Start only the local llama server (needs the stack running; never stops a running container)"
_help_line "stop-llama" "Stop only the local llama server"
_help_line "llama-enable" "Enable local llama inference with MODEL=<alias> in models.yml (backs up the file; then run 'make start-llama')"
_help_line "llama-disable" "Disable local llama inference in models.yml (backs up the file)"
_help_line "check-setup" "Validate config, image, models, GPU (offline)"
_help_line "check-server" "Validate the running server API (online)"
_help_line "check-with-agents" "Opt-in independent agent inference checks"
_help_line "benchmark" "Benchmark Vulkan and record results, with CPU fallback (run after 'make stop-llama'; a failed Vulkan run rewrites gpu.backend/gpu.image in models.yml)"
_help_line "system-one-build" "Build the local System One (Laya) GPU image"
_help_line "system-one-benchmark" "Benchmark the running System One server and record the load table"
_help_line "resources-snapshot" "Point-in-time snapshot: per-service CPU/RAM policy, overrides and live cgroup counters with an OK/WATCH/ALERT verdict (read-only, no load)"
_help_line "model-interference" "Measure whether the local model slows System One or pressures container memory (writes tmp/model-interference/)"
_help_line "model-capacity" "Write and show the capacity card from measured data (models.yml, DEPTH=bench json, SCORE=score json, PROFILE=latency-profile json)"
_help_line "model-report" "One-page plain-text report of a model from its capacity card (MODEL=alias; saved as capacity/<alias>.report.md)"
_help_line "resources-benchmark" "Measure a container to re-derive its limits (SERVICE=omniroute|attach|report; tmp/resource-benchmark/)"
_help_line "key-reset" "Generate a new API key"
_help_line "show-secrets" "Print the API key and OmniRoute dashboard password"
_help_line "enable-boot" "Start automatically at boot"
_help_line "disable-boot" "Do not start at boot"
_help_line "status" "Show service status"
_help_line "gpu-status" "Show live dGPU contention; optionally migrate offenders to the iGPU"
_help_line "desktop-gpu-reset" "Remove a leftover desktop default-GPU override (use 'cardwire' to choose the default GPU)"
_help_line "desktop-gpu-status" "Show detected GPUs and which one is active"
_help_line "codex-provision" "Import local Codex CLI session into OmniRoute (match by account email)"
