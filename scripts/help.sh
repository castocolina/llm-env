_help_line "connections-backup" "Back up OmniRoute provider connection metadata only (OUTPUT=path optional)"
_help_line "update-omniroute" "Pull a newer OmniRoute image if one is published, then stop/start"
_help_line "check-provider-tokens" "Flag any OmniRoute provider connection needing attention (auth, quota, billing, policy)"
